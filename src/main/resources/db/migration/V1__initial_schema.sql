CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(40) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(180) NOT NULL,
    event_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    venue VARCHAR(220) NOT NULL
);

CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number VARCHAR(80) NOT NULL UNIQUE,
    full_name VARCHAR(180) NOT NULL,
    program VARCHAR(80) NOT NULL
);

CREATE TABLE event_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    credential_token VARCHAR(80) NOT NULL UNIQUE,
    CONSTRAINT fk_registration_event FOREIGN KEY (event_id) REFERENCES events(id),
    CONSTRAINT fk_registration_student FOREIGN KEY (student_id) REFERENCES students(id),
    CONSTRAINT uq_event_student UNIQUE (event_id, student_id)
);

CREATE TABLE scanner_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    scanner_name VARCHAR(120) NOT NULL,
    pairing_token VARCHAR(100) NOT NULL UNIQUE,
    device_id VARCHAR(100) UNIQUE,
    paired BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    paired_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_scanner_event FOREIGN KEY (event_id) REFERENCES events(id)
);

CREATE TABLE attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    registration_id BIGINT NOT NULL,
    scanner_device_id BIGINT NOT NULL,
    checked_in_at TIMESTAMP WITH TIME ZONE NOT NULL,
    synced_at TIMESTAMP WITH TIME ZONE NOT NULL,
    client_transaction_id VARCHAR(100) NOT NULL UNIQUE,
    source VARCHAR(20) NOT NULL,
    CONSTRAINT fk_attendance_event FOREIGN KEY (event_id) REFERENCES events(id),
    CONSTRAINT fk_attendance_registration FOREIGN KEY (registration_id) REFERENCES event_registrations(id),
    CONSTRAINT fk_attendance_scanner FOREIGN KEY (scanner_device_id) REFERENCES scanner_devices(id),
    CONSTRAINT uq_event_registration_attendance UNIQUE (event_id, registration_id)
);

CREATE TABLE certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certificate_id VARCHAR(80) NOT NULL UNIQUE,
    registration_id BIGINT NOT NULL UNIQUE,
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_certificate_registration FOREIGN KEY (registration_id) REFERENCES event_registrations(id)
);

CREATE INDEX idx_registration_event ON event_registrations(event_id);
CREATE INDEX idx_attendance_event ON attendance(event_id);
CREATE INDEX idx_scanner_event ON scanner_devices(event_id);
